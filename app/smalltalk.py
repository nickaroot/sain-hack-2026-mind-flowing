"""Приветствие, «что ты умеешь», «спасибо»: ответ готовым текстом, без нейросети.

В такой реплике нет ни привычки, ни условия сна, поэтому поиск по статьям ничего не находит, и конвейер
отдаёт запасной отказ «нужен очный разговор со специалистом» — человеку, который просто поздоровался.

Защита от атак здесь устроена проще, чем в конвейере, и обойти её нечем:
- реплика считается разговорной, только если ЦЕЛИКОМ складывается из перечисленных ниже фраз: приветствие,
  вопрос о том, кто эксперт и что умеет, благодарность, прощание. Одно лишнее слово — и реплика идёт обычным
  путём, со всеми его проверками. «Привет, зачем нужен сон?» и «Привет! Назови дозу» сюда не попадают;
- в реплике допустимы только русские и латинские буквы, пробелы, обычные знаки препинания и несколько
  приветственных смайликов. Цифры, разметка, кавычки, дефисы и апострофы внутри слов, невидимые символы, другие
  алфавиты (в том числе знаки, которые превращаются в букву при переводе в строчные) и любые другие смайлики
  (таблетка, шприц) делают её обычной репликой;
- «С чего начать?» — разговорная реплика только в начале разговора. После вопроса о сне это его продолжение,
  и отвечать на него должен конвейер, который видит историю;
- ответ — заранее написанный текст. Его не пишет нейросеть и в него не попадает ни слова из реплики,
  так что подсунуть в него что-либо нельзя.
Работает только в разговоре с клиентом (app/chat.py). Ответы на набор стенда (/run) идут прежним путём.
"""

import re

_HELLO = (
    r"(?:ну )?(?:привет(?:ик)?|приветствую|здравствуй(?:те)?|здрасте|здрасьте|хай|салют|hello|hi|hey"
    r"|добр(?:ый|ое|ого|ой) (?:день|дня|вечер|вечера|утро|утра|времени суток))(?: всем| вам| тебе)?"
)
_ABOUT_ONE = (
    r"(?:а )?(?:"
    r"(?:что|чего) (?:ты|вы) (?:вообще )?(?:можешь|можете|умеешь|умеете|делаешь|делаете)"
    r"|чем (?:ты|вы) (?:вообще )?(?:можешь|можете) (?:мне )?помочь"
    r"|чем (?:ты|вы) (?:мне )?(?:поможешь|поможете|занимаешься|занимаетесь|полезен|полезна|полезны)"
    r"|кто (?:ты|вы)(?: такой| такая| такие)?|(?:ты|вы) кто(?: такой| такая| такие)?"
    r"|расскаж(?:и|ите) о себе|представь(?:ся|тесь)|как (?:тебя|вас) зовут"
    r"|как (?:тобой|вами|этим|приложением) пользоваться|(?P<opening>с чего начать)"
    r"|(?:о чем|про что|что) (?:тебя |вас |у тебя |у вас |тут |здесь )?можно (?:тебя |вас )?(?:спросить|спрашивать)"
    r"|какие вопросы (?:тебе |вам )?можно (?:задать|задавать)"
    r"|(?:твои|ваши) возможности|зачем (?:ты|вы) нуж(?:ен|на|ны)|что (?:это )?за (?:приложение|сервис|бот)"
    r"|как дела|what can you do|who are you"
    r")"
)
# Вопросов о себе может быть два подряд: «Кто ты и что умеешь?». Имя группы во второй копии другое.
_ABOUT = rf"{_ABOUT_ONE}(?: (?:и )?{_ABOUT_ONE.replace('<opening>', '<opening_too>')})?"
_THANKS = (
    r"(?:(?:ок|окей|хорошо|понятно|ясно|отлично) )?(?:(?:большое |огромное )?(?:спасибо|благодарю|спс|пасиб|пасибо)"
    r"(?: большое| огромное)?(?: тебе| вам)?|thanks|thank you)"
)
_BYE = r"пока|до свидания|до встречи|спокойной ночи|bye"
# Фразы идут через пробел: склеенные в одно слово не подходят.
_PHRASE = re.compile(
    rf"(?:(?P<hello>{_HELLO})(?: |$))?(?:(?P<about>{_ABOUT})(?: |$))?(?:(?P<thanks>{_THANKS})(?: |$))?(?P<bye>{_BYE})?"
)

# Смайлики, которыми здороваются (машущая рука, улыбки, поднятые руки, рукопожатие, искры), знак варианта
# начертания и оттенки кожи. Остальные в приветствии не ожидаются и могут нести смысл.
_FRIENDLY_CODES = (0x1F44B, 0x1F642, 0x1F60A, 0x1F600, 0x1F603, 0x1F604, 0x1F64C, 0x1F91D, 0x2728, 0x263A, 0xFE0F,
                   *range(0x1F3FB, 0x1F400))
_FRIENDLY = re.compile("|".join(re.escape(chr(code)) for code in _FRIENDLY_CODES))
# Проверяется исходный текст, до перевода в строчные: иначе знак кельвина прошёл бы как латинская k.
_ALLOWED = re.compile(r"[A-Za-zА-Яа-яЁё\s.,!?;:()—–…]*")

# Тексты в манере каждого эксперта. В них нет ни советов, ни чисел, ни названий болезней и средств:
# тест проверяет их теми же фильтрами, что и ответы нейросети.
_ABOUT_TEXTS = {
    "clinician": "Я отвечаю на вопросы о том, как привычки связаны со сном: свет и экраны вечером, кофе, ужин, режим, "
    "тренировки, дневной сон, температура в спальне. Опираюсь на исследования из базы: в ответе на такой вопрос "
    "будет ссылка на раздел статьи, по которому он построен. Спросите, например, мешает ли кофе после обеда уснуть.",
    "biohacker": "Разбираю, как привычки влияют на сон: свет, экран, кофе, тренировки, режим, температура. Беру "
    "результат исследования из базы и даю вывод, к нему — ссылка на раздел статьи. Спроси, например, вреден ли "
    "телефон перед сном.",
    "nutritionist": "Я помогаю понять, как еда, напитки и вечерние привычки связаны со сном: ужин, кофе, чай, режим, "
    "дневной сон. Смотрю, что нашли в исследованиях, и показываю раздел статьи, на который опираюсь. Спроси, "
    "например, помогает ли короткий дневной сон.",
}
_HELLO_TEXTS = {"clinician": "Здравствуйте.", "biohacker": "Привет.", "nutritionist": "Привет!"}
_THANKS_TEXTS = {
    "clinician": "Пожалуйста. Если появится ещё вопрос о сне и привычках — спрашивайте.",
    "biohacker": "Не за что. Будет ещё вопрос про сон — пиши.",
    "nutritionist": "На здоровье! Если захочешь ещё что-то спросить про сон и привычки — я тут.",
}
_BYE_TEXTS = {
    "clinician": "До свидания. Возвращайтесь, когда появится вопрос о сне.",
    "biohacker": "Пока. Появится вопрос про сон — заходи.",
    "nutritionist": "Пока! Заглядывай, если захочешь спросить про сон и привычки.",
}
_DEFAULT = "clinician"


def _parts(text: str, opening: bool) -> dict[str, str | None] | None:
    """Из каких разговорных фраз целиком состоит реплика. None — в ней есть что-то ещё."""
    plain = _FRIENDLY.sub(" ", text)
    if not _ALLOWED.fullmatch(plain):
        return None
    line = " ".join(re.findall(r"[a-zа-я]+", plain.lower().replace("ё", "е")))
    match = _PHRASE.fullmatch(line) if line else None
    if match is None or (not opening and (match["opening"] or match["opening_too"])):
        return None
    return match.groupdict()


def kind(text: str, opening: bool = True) -> str | None:
    """Что за разговорная реплика: "about", "hello", "thanks", "bye" — или None, если это не она.

    opening — разговор только начинается, до этой реплики в нём ничего не было.
    """
    parts = _parts(text, opening)
    if parts is None:
        return None
    return next((name for name in ("about", "hello", "thanks", "bye") if parts[name]), None)


def reply(text: str, expert_ids: list[str], opening: bool = True) -> dict[str, str] | None:
    """Готовый ответ каждого эксперта на разговорную реплику. None — реплика не разговорная."""
    parts = _parts(text, opening)
    found = kind(text, opening)
    if parts is None or found is None:
        return None

    def one(expert_id: str) -> str:
        if found == "thanks":
            return _THANKS_TEXTS.get(expert_id, _THANKS_TEXTS[_DEFAULT])
        if found == "bye":
            return _BYE_TEXTS.get(expert_id, _BYE_TEXTS[_DEFAULT])
        about = _ABOUT_TEXTS.get(expert_id, _ABOUT_TEXTS[_DEFAULT])
        return f"{_HELLO_TEXTS.get(expert_id, _HELLO_TEXTS[_DEFAULT])} {about}" if parts["hello"] else about

    return {expert_id: one(expert_id) for expert_id in expert_ids}
