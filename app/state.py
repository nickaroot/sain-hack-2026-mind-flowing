"""Состояние процесса: что решение помнит между запросами и кто этим владеет.

Всё состояние живёт в памяти одного процесса. Это осознанный выбор под условия стенда — один процесс,
1 CPU, 512 МБ, запись только в /tmp, внешних хранилищ нет:

    что                     где                    как ограничено и когда пропадает
    прогоны набора          app.state.runs         по одному на код набора и токен; после сбоя забывается
    последний набор         app.state.dataset      один; заменяется следующим /run
    учёт токенов за сутки   chat.ChatState         счётчики; сброс в 00:00 по Москве
    ответы разговоров       chat.ChatState.cache   200 последних
    ответы нейросети        app.state.responses    600 записей и 8 МБ; только ответы без замечаний
                            chat.ChatState         свои 200 записей и 2 МБ: разговор не влияет на прогон
    распознанные записи     voice.VoiceState       50 последних
    индекс базы статей      chat.ChatState         один на набор
    озвученные ответы       voice.VoiceState       30 записей и 16 МБ
    темп обращений к прокси llm._next_start        одно число на процесс: общий для нейросети и голоса

Проверка и изменение счётчиков стоят рядом, без await между ними: в одном цикле событий это и есть
атомарность. Перезапуск обнуляет всё; для зачётного прогона это безопасно, потому что /run считает набор
заново. Как это состояние выносится наружу при нескольких экземплярах — в docs/ARCHITECTURE.md.
"""

import asyncio
from datetime import datetime, timedelta, timezone

from fastapi import FastAPI

from app import config
from app.cache import ResponseCache

MOSCOW = timezone(timedelta(hours=3))  # суточные лимиты прокси сбрасываются в 00:00 по Москве


def moscow_day() -> str:
    """Сегодняшняя дата по Москве: ключ, по которому сбрасываются суточные счётчики."""
    return datetime.now(MOSCOW).date().isoformat()


def init(app: FastAPI) -> None:
    """Заводит состояние приложения. Состояния разговоров и голоса создаются при первом обращении."""
    # Последний полученный набор: после /run финального показа клиент работает с ним.
    app.state.dataset = None
    # Прогоны по коду набора. Повторный /run с тем же кодом (например, после обрыва связи у вызывающей
    # стороны) получает тот же результат и не тратит суточный лимит токенов второй раз.
    app.state.runs = {}
    # Прошёл ли в этом процессе прогон набора: после него разговорам в клиенте отдаётся больший запас токенов.
    app.state.run_finished = False
    # Пригодные ответы нейросети для прогонов набора, см. app/cache.py. У разговоров память своя.
    app.state.responses = ResponseCache(config.RESPONSE_CACHE_ITEMS, config.RESPONSE_CACHE_BYTES)
    app.state.chat = None
    app.state.voice = None


def run_active(app: FastAPI) -> bool:
    """Идёт ли прогон набора: на это время методы клиента уступают ему лимиты прокси."""
    runs: dict[tuple, asyncio.Task] = app.state.runs
    return any(not task.done() for task in runs.values())
