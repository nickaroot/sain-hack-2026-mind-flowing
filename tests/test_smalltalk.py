@pytest.mark.parametrize(("text", "kind"), SMALL_TALK)
def test_small_talk_is_recognised(text, kind):
    assert smalltalk.kind(text) == kind


@pytest.mark.parametrize("text", NOT_SMALL_TALK)
def test_anything_with_a_real_request_goes_the_usual_way(text):
    assert smalltalk.kind(text) is None and smalltalk.reply(text, EXPERTS) is None


@pytest.mark.parametrize("text", ["С чего начать?", "Привет, с чего начать?", "Кто ты и с чего начать?"])
def test_where_to_start_is_small_talk_only_when_the_talk_begins(text):
    # После вопроса о сне «с чего начать?» — его продолжение: на него отвечает конвейер, который видит историю.
    assert smalltalk.kind(text) == "about" and smalltalk.reply(text, EXPERTS)
    assert smalltalk.kind(text, opening=False) is None and smalltalk.reply(text, EXPERTS, opening=False) is None


def test_other_small_talk_does_not_depend_on_history():
    assert [smalltalk.kind(text, opening=False) for text, _ in SMALL_TALK] == [kind for _, kind in SMALL_TALK]


def test_phrases_have_no_words_a_real_request_is_made_of():
    # Набор фраз — вся защита этого пути: в нём не должно появиться слов, из которых складывается просьба по существу.
    risky = ["доз", "диагноз", "болезн", "лекарств", "таблет", "мелатонин", "назнач", "выпи", "посовет", "пить",
             "приним", "лечи", "забуд", "игнорир", "правил", "инструкц", "роль", "врач", "промпт", "сон", "сне", "спать"]
    assert not [word for word in risky if word in smalltalk._PHRASE.pattern]


@pytest.mark.parametrize("text", ["Привет. Что ты можешь?", "Что ты умеешь?", "Спасибо", "Пока"])
def test_ready_texts_pass_the_same_filters_as_model_answers(text):
    replies = smalltalk.reply(text, [*EXPERTS, "новый эксперт"])
    assert set(replies) == {*EXPERTS, "новый эксперт"}
    for reply in replies.values():
        assert is_safe_text(reply)
        assert not [p for p in text_problems(reply, refused=False) if p.substantive]
        assert reply not in pipeline.FALLBACK_TEXTS.values()


def test_greeting_is_answered_only_when_the_person_greeted():
    assert smalltalk.reply("Привет. Что ты можешь?", ["clinician"])["clinician"].startswith("Здравствуйте.")
    assert not smalltalk.reply("Что ты можешь?", ["clinician"])["clinician"].startswith("Здравствуйте.")
